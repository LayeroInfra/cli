/**
 * Ссылка на проект: идентификатор или слаг, и как одно отличить от другого.
 *
 * 🚨 ОТДЕЛЬНЫЙ МОДУЛЬ РАДИ ОДНОЙ СТРОКИ — намеренно. Форма UUID нужна и
 * клиенту API, и команде деплоя; жила она копией в `commands/deploy.ts`, и
 * второй копией разошлась бы молча. Положить её в `api.ts` не вышло: тесты
 * подменяют этот модуль целиком (`vi.mock`), и константа исчезала бы вместе с
 * ним — то есть общий модуль стал бы способом уронить чужой тест.
 */

export const UUID_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Что нам дали — идентификатор или слаг.
 *
 * ⚠️ Отличаем по ФОРМЕ, а не по успеху запроса: UUID, ушедший в поиск по
 * слагу, просто не найдётся, и человек получит «нет такого проекта» на
 * совершенно правильный идентификатор.
 */
export function looksLikeId(ref: string): boolean {
  return UUID_RE.test(ref);
}
